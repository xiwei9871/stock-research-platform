"""CAP-R2C P4 — verification task status ledger.

Append-only per-theme ledger under the research workbench dir.  Status
transitions are always recorded with a timestamp and reason — a refresh
can NEVER silently overwrite a prior verdict:

  proposed  — task currently generated by the gap/rules engine
  resolved  — task no longer generated (its gap closed); keeps history
  reopened  — resolved task re-surfaced, OR a new material
              counter-evidence change touched its node

Duplicate re-ingestion of the same task_id is a no-op (stable identity +
single history entry).  A material change with ``direction=counter`` on
a task's node reopens it; non-substantive same-source duplicates do not.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


def _ledger_path(workbench_dir: str, theme_id: str) -> Path:
    return Path(workbench_dir) / theme_id / "verification_ledger.json"


def load_task_ledger(workbench_dir: str, theme_id: str) -> dict[str, Any]:
    p = _ledger_path(workbench_dir, theme_id)
    if p.exists():
        return json.loads(p.read_text(encoding="utf-8"))
    return {"theme_id": theme_id, "tasks": {}}


def update_task_ledger(
    workbench_dir: str,
    theme_id: str,
    current_tasks: list[dict[str, Any]],
    material_changes: list[dict[str, Any]],
    now: str | None = None,
) -> dict[str, Any]:
    """Fold the freshly generated task list + material changes into the
    persisted ledger.  Returns (and writes) the updated ledger."""
    at = now or datetime.now(timezone.utc).isoformat(timespec="seconds")
    ledger = load_task_ledger(workbench_dir, theme_id)
    tasks: dict[str, Any] = ledger.setdefault("tasks", {})
    current_ids = {t["task_id"] for t in current_tasks}

    def _hist(entry: dict[str, Any], status: str, reason: str) -> None:
        entry.setdefault("history", []).append(
            {"at": at, "status": status, "reason": reason})

    for t in current_tasks:
        tid = t["task_id"]
        entry = tasks.get(tid)
        if entry is None:
            entry = tasks[tid] = {
                "verification_status": "proposed",
                "history": [],
                "research_gap_id": t.get("research_gap_id"),
                "node_id": t.get("node_id"),
                "company_code": t.get("company_code"),
                "related_node_ids": t.get("related_node_ids") or [],
                "last_material_change": None,
            }
            _hist(entry, "proposed", "generated_by_gap_engine")
            continue
        if entry["verification_status"] == "resolved":
            entry["verification_status"] = "reopened"
            _hist(entry, "reopened", "gap_resurfaced_in_current_run")
        entry["related_node_ids"] = sorted(set(
            entry.get("related_node_ids") or []) |
            set(t.get("related_node_ids") or []))
        if t.get("research_gap_id"):
            entry["research_gap_id"] = t["research_gap_id"]

    for tid, entry in tasks.items():
        if tid in current_ids:
            continue
        if entry["verification_status"] in {"proposed", "reopened"}:
            entry["verification_status"] = "resolved"
            _hist(entry, "resolved", "gap_closed_not_regenerated")

    counter_changes = [
        c for c in material_changes
        if c.get("materiality") == "material" and (
            c.get("direction") == "counter"
            # same_source_new_fact reaching materiality is, by
            # construction, a new qualified COUNTER fact (see
            # classify_changes / _evidence_materiality)
            or c.get("change_category") == "same_source_new_fact")]
    for ch in counter_changes:
        ch_nodes = {ch.get("node_id") or ""} | set(
            ch.get("related_node_ids") or [])
        change_ref = {
            "at": at,
            "field": ch.get("field"),
            "change_category": ch.get("change_category"),
            "summary": f"{ch.get('field')}:{ch.get('from')}→{ch.get('to')}",
        }
        for tid, entry in tasks.items():
            nodes = {entry.get("node_id") or ""} | set(
                entry.get("related_node_ids") or [])
            if not (nodes & ch_nodes):
                continue
            entry["last_material_change"] = change_ref
            if entry["verification_status"] != "reopened":
                entry["verification_status"] = "reopened"
                _hist(entry, "reopened",
                      f"material_counter:{ch.get('field')}")

    p = _ledger_path(workbench_dir, theme_id)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(ledger, ensure_ascii=False, indent=1),
                 encoding="utf-8")
    return ledger
